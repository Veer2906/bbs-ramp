export type PixelName = keyof typeof BITMAPS;

export function Px({ name, className }: { name: PixelName; className?: string }) {
  const rows = BITMAPS[name];
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const s = Math.max(w, h);
  const ox = (s - w) / 2;
  const oy = (s - h) / 2;
  return (
    <svg viewBox={`0 0 ${s} ${s}`} className={className ?? "size-3.5"} fill="currentColor" shapeRendering="crispEdges" aria-hidden>
      {rows.flatMap((r, y) => r.split("").map((c, x) => (c === "#" ? <rect key={`${x}-${y}`} x={x + ox} y={y + oy} width={1} height={1} /> : null)))}
    </svg>
  );
}
