export type PixelName = keyof typeof BITMAPS;

export function Px({ name, scale = 2, className, style }: { name: PixelName; scale?: number; className?: string; style?: CSSProperties }) {
  const rows = BITMAPS[name];
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  return (
    <svg
      viewBox={`0 0 ${w} ${h}`}
      width={w * scale}
      height={h * scale}
      className={className}
      style={{ flexShrink: 0, ...style }}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden
    >
      {rows.flatMap((r, y) => r.split("").map((c, x) => (c === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} /> : null)))}
    </svg>
  );
}
